import { describe, it, expect, beforeEach, vi, afterEach } from 'vitest';
import { AiCacheService, generateCacheKey } from '../src/modules/ai/cache';
import { SingleFlightCoordinator } from '../src/modules/ai/singleFlight';
import { AiCircuitBreaker, CircuitBreakerOpenError, aiCircuitBreaker } from '../src/modules/ai/circuitBreaker';
import { callGemini, GeminiQuotaExhaustedError } from '../src/modules/ai/geminiClient';
import { executeResilientAi } from '../src/modules/ai/orchestrator';
import { aiMetrics } from '../src/modules/ai/metrics';
import request from 'supertest';
import { app } from '../src/app';
import { signToken } from '../src/middleware/auth';
import { db } from '../src/config/database';

describe('LogiSphere AI — Smart Caching, Resilience & Fallback Architecture', () => {
  let cache: AiCacheService;
  let singleFlight: SingleFlightCoordinator;
  let circuitBreaker: AiCircuitBreaker;

  beforeEach(() => {
    cache = new AiCacheService(5, 60000); // Small capacity (5) for eviction testing
    singleFlight = new SingleFlightCoordinator();
    circuitBreaker = new AiCircuitBreaker({ failureThreshold: 2, cooldownMs: 500 });
    aiCircuitBreaker.reset();
    aiMetrics.reset();
    vi.restoreAllMocks();
  });

  afterEach(() => {
    cache.destroy();
  });

  // 1. Cache hit: Gemini is not called again
  it('1. Cache hit: returns cached data without invoking Gemini provider', async () => {
    const key = 'test-key-1';
    cache.set(key, { explanation: 'Cached analysis' }, 60, 'TRIP_DELAY_INSIGHTS');

    const providerSpy = vi.fn().mockResolvedValue({ explanation: 'Fresh analysis' });

    // Mock cache lookup in orchestrator
    const result = await executeResilientAi({
      feature: 'TRIP_DELAY_INSIGHTS',
      normalizedInput: { tripId: 'TRP-101' },
      executeGemini: providerSpy,
      getFallback: () => ({ explanation: 'Fallback analysis' }),
    });

    // First call calls Gemini
    expect(providerSpy).toHaveBeenCalledTimes(1);

    // Second identical call hits cache
    const cachedResult = await executeResilientAi({
      feature: 'TRIP_DELAY_INSIGHTS',
      normalizedInput: { tripId: 'TRP-101' },
      executeGemini: providerSpy,
      getFallback: () => ({ explanation: 'Fallback analysis' }),
    });

    expect(providerSpy).toHaveBeenCalledTimes(1); // Not called again!
    expect(cachedResult).toEqual(result);
  });

  // 2. Cache miss: Gemini is called
  it('2. Cache miss: provider is executed when key is not cached', async () => {
    const providerSpy = vi.fn().mockResolvedValue({ explanation: 'Generated by Gemini' });

    const result = await executeResilientAi({
      feature: 'MAINTENANCE_FORECAST',
      normalizedInput: { month: '2026-11' },
      executeGemini: providerSpy,
      getFallback: () => ({ explanation: 'Fallback' }),
    });

    expect(providerSpy).toHaveBeenCalledTimes(1);
    expect(result).toEqual({ explanation: 'Generated by Gemini' });
  });

  // 3. Expired cache entry: a new request is made
  it('3. Expired cache entry: new provider call is triggered after TTL expiry', async () => {
    const testCache = new AiCacheService(50);
    const key = 'expiry-test-key';
    testCache.set(key, { data: 'old' }, 1, 'TRIP_DELAY_INSIGHTS'); // 1s TTL

    expect(testCache.get(key)).toEqual({ data: 'old' });

    // Fast-forward time past 1s
    const originalNow = Date.now;
    try {
      Date.now = vi.fn(() => originalNow() + 2000);
      expect(testCache.get(key)).toBeNull(); // Expired!
    } finally {
      Date.now = originalNow;
      testCache.destroy();
    }
  });

  // 4. Concurrent identical requests: eligible requests share one computation (single-flight)
  it('4. Concurrent identical requests: coalesces in-flight calls to single execution', async () => {
    let callCount = 0;
    const slowProvider = async () => {
      callCount++;
      await new Promise((r) => setTimeout(r, 50));
      return { output: 'coalesced-success' };
    };

    const key = 'in-flight-key-1';
    const [res1, res2, res3] = await Promise.all([
      singleFlight.do(key, slowProvider),
      singleFlight.do(key, slowProvider),
      singleFlight.do(key, slowProvider),
    ]);

    expect(callCount).toBe(1); // Only ONE execution happened!
    expect(res1.result).toEqual({ output: 'coalesced-success' });
    expect(res2.result).toEqual({ output: 'coalesced-success' });
    expect(res3.result).toEqual({ output: 'coalesced-success' });
    expect(res2.wasCoalesced).toBe(true);
    expect(res3.wasCoalesced).toBe(true);
  });

  // 5. Different input or model: cache entries remain separate
  it('5. Different input or model: generates distinct cache keys and separate entries', () => {
    const keyModelA = generateCacheKey({
      feature: 'ROUTE_RECOMMENDATION',
      model: 'gemini-1.5-flash',
      normalizedInput: { origin: 'A', dest: 'B' },
    });

    const keyModelB = generateCacheKey({
      feature: 'ROUTE_RECOMMENDATION',
      model: 'gemini-1.5-pro',
      normalizedInput: { origin: 'A', dest: 'B' },
    });

    const keyDifferentInput = generateCacheKey({
      feature: 'ROUTE_RECOMMENDATION',
      model: 'gemini-1.5-flash',
      normalizedInput: { origin: 'A', dest: 'C' },
    });

    expect(keyModelA).not.toEqual(keyModelB);
    expect(keyModelA).not.toEqual(keyDifferentInput);
  });

  // 6. Tenant/user isolation: unauthorized cached data is never returned
  it('6. Tenant/user isolation: user-specific cache keys never collide across users', () => {
    const driver1Key = generateCacheKey({
      feature: 'AI_ASSISTANT_QUERY',
      model: 'gemini-1.5-flash',
      tenantOrUserId: 'driver_user_1',
      normalizedInput: { query: 'my attendance' },
    });

    const driver2Key = generateCacheKey({
      feature: 'AI_ASSISTANT_QUERY',
      model: 'gemini-1.5-flash',
      tenantOrUserId: 'driver_user_2',
      normalizedInput: { query: 'my attendance' },
    });

    expect(driver1Key).not.toEqual(driver2Key);
    expect(driver1Key).toContain('driver_user_1');
    expect(driver2Key).toContain('driver_user_2');
  });

  // 7. Successful Gemini response: validated response is returned and cached
  it('7. Successful Gemini response: validated response is cached and returned', async () => {
    const validData = { explanation: 'Everything is optimal', confidence: 'high' };
    const provider = vi.fn().mockResolvedValue(validData);

    const result = await executeResilientAi({
      feature: 'TRIP_DELAY_INSIGHTS',
      normalizedInput: { tripId: 'TRP-VAL-1' },
      executeGemini: provider,
      validateResponse: (res) => res && res.confidence === 'high',
      getFallback: () => ({ explanation: 'fallback', confidence: 'low' }),
    });

    expect(result).toEqual(validData);
  });

  // 8. Temporary 5xx/network failure: bounded retry behavior works
  it('8. Temporary 5xx/network failure: retries transient errors and succeeds upon retry', async () => {
    let attempts = 0;
    const globalFetch = global.fetch;

    try {
      global.fetch = vi.fn().mockImplementation(async () => {
        attempts++;
        if (attempts === 1) {
          // First attempt fails with 503 Service Unavailable
          return {
            ok: false,
            status: 503,
            text: async () => 'Service Unavailable',
            headers: new Headers(),
          };
        }
        // Second attempt succeeds
        return {
          ok: true,
          status: 200,
          json: async () => ({
            candidates: [{ content: { parts: [{ text: JSON.stringify({ ok: true }) }] } }],
          }),
        };
      });

      const res = await callGemini({
        userPrompt: 'test prompt',
        responseMimeType: 'application/json',
        maxRetries: 2,
        timeoutMs: 1000,
      });

      expect(attempts).toBe(2);
      expect(res.data).toEqual({ ok: true });
    } finally {
      global.fetch = globalFetch;
    }
  });

  // 9. Daily quota exhaustion: retries stop immediately and fallback is used
  it('9. Daily quota exhaustion: detects RESOURCE_EXHAUSTED, immediately aborts retries and uses fallback', async () => {
    let callCount = 0;
    const globalFetch = global.fetch;

    try {
      global.fetch = vi.fn().mockImplementation(async () => {
        callCount++;
        return {
          ok: false,
          status: 429,
          text: async () => 'RESOURCE_EXHAUSTED: Daily quota exceeded for quota metric GenerateContent',
          headers: new Headers(),
        };
      });

      const fallback = { status: 'safe-fallback' };
      const result = await executeResilientAi<any>({
        feature: 'MAINTENANCE_FORECAST',
        normalizedInput: { test: 'quota-check' },
        executeGemini: async () => {
          return await callGemini({
            userPrompt: 'prompt',
            maxRetries: 2,
          });
        },
        getFallback: () => fallback,
      });

      // Crucial: Must NOT retry 3 times on daily quota exhaustion! Exactly 1 call attempted
      expect(callCount).toBe(1);
      expect(result).toEqual(fallback);
    } finally {
      global.fetch = globalFetch;
    }
  });

  // 10. Invalid API key or client error (400, 401, 403, 404): no pointless retries
  it('10. Client / Auth error (400, 404): halts retries immediately without wasteful attempts', async () => {
    let callCount = 0;
    const globalFetch = global.fetch;

    try {
      global.fetch = vi.fn().mockImplementation(async () => {
        callCount++;
        return {
          ok: false,
          status: 400,
          text: async () => 'Invalid argument provided',
          headers: new Headers(),
        };
      });

      await expect(
        callGemini({
          userPrompt: 'malformed query',
          maxRetries: 2,
        })
      ).rejects.toThrow();

      // Exactly 1 call, zero wasteful retries on 400 client error
      expect(callCount).toBe(1);
    } finally {
      global.fetch = globalFetch;
    }
  });

  // 11. Malformed AI response: it is not cached as a valid result
  it('11. Malformed AI response: fails validation, uses fallback and does not pollute cache', async () => {
    const fallback = { valid: true, source: 'fallback' };
    const provider = vi.fn().mockResolvedValue({ corrupted: true }); // Malformed

    const result = await executeResilientAi({
      feature: 'ROUTE_RECOMMENDATION',
      normalizedInput: { tripId: 'TRP-CORRUPT' },
      executeGemini: provider,
      validateResponse: (res: any) => Boolean(res && res.valid === true),
      getFallback: () => fallback,
    });

    expect(result).toEqual(fallback);

    // Call again to verify malformed response was NOT cached
    await executeResilientAi({
      feature: 'ROUTE_RECOMMENDATION',
      normalizedInput: { tripId: 'TRP-CORRUPT' },
      executeGemini: provider,
      validateResponse: (res: any) => Boolean(res && res.valid === true),
      getFallback: () => fallback,
    });

    // Provider called again because bad data was discarded
    expect(provider).toHaveBeenCalledTimes(2);
  });

  // 12. Cache eviction and bounded memory: capacity limit evicts oldest entries
  it('12. Cache eviction: bounded LRU cache evicts oldest entry when max capacity is reached', () => {
    const boundedCache = new AiCacheService(3); // Cap of 3

    boundedCache.set('k1', 'val1', 100, 'TRIP_DELAY_INSIGHTS');
    boundedCache.set('k2', 'val2', 100, 'TRIP_DELAY_INSIGHTS');
    boundedCache.set('k3', 'val3', 100, 'TRIP_DELAY_INSIGHTS');
    expect(boundedCache.getStats().size).toBe(3);

    // Adding 4th entry evicts oldest (k1)
    boundedCache.set('k4', 'val4', 100, 'TRIP_DELAY_INSIGHTS');
    expect(boundedCache.getStats().size).toBe(3);
    expect(boundedCache.get('k1')).toBeNull(); // k1 was evicted!
    expect(boundedCache.get('k2')).toBe('val2');
    expect(boundedCache.get('k4')).toBe('val4');

    boundedCache.destroy();
  });

  // 13. Circuit Breaker Trips and Recovers: CLOSED -> OPEN -> HALF_OPEN -> CLOSED
  it('13. Circuit Breaker: trips after consecutive failures and recovers on probe success', () => {
    const cb = new AiCircuitBreaker({ failureThreshold: 2, cooldownMs: 100 });
    expect(cb.getState()).toBe('CLOSED');
    expect(cb.canExecute()).toBe(true);

    // 1st failure
    cb.recordFailure(true);
    expect(cb.getState()).toBe('CLOSED');

    // 2nd qualifying failure -> trips to OPEN
    cb.recordFailure(true);
    expect(cb.getState()).toBe('OPEN');
    expect(cb.canExecute()).toBe(false);

    // Fast-fail check
    expect(() => {
      if (!cb.canExecute()) throw new CircuitBreakerOpenError();
    }).toThrow('Circuit Breaker is OPEN');
  });

  // 14. Metrics & Stats endpoint accessible by authenticated managers
  it('14. GET /api/ai/metrics returns telemetry and requires manager authentication', async () => {
    // 1. Unauthenticated request -> 401
    const unauthRes = await request(app).get('/api/ai/metrics');
    expect(unauthRes.status).toBe(401);

    // 2. Driver role -> 403 Forbidden
    const driverToken = signToken({ id: 'drv-metrics', email: 'drv@logi.ai', role: 'ROLE_DRIVER' });
    const driverRes = await request(app)
      .get('/api/ai/metrics')
      .set('Authorization', `Bearer ${driverToken}`);
    expect(driverRes.status).toBe(403);

    // 3. Manager role -> 200 OK with metrics & cache telemetry
    const mgrToken = signToken({ id: 'mgr-metrics', email: 'mgr@logi.ai', role: 'ROLE_MANAGER' });
    const mgrRes = await request(app)
      .get('/api/ai/metrics')
      .set('Authorization', `Bearer ${mgrToken}`);

    expect(mgrRes.status).toBe(200);
    expect(mgrRes.body.success).toBe(true);
    expect(mgrRes.body.data).toHaveProperty('metrics');
    expect(mgrRes.body.data).toHaveProperty('cache');
    expect(mgrRes.body.data).toHaveProperty('circuitBreaker');
    expect(mgrRes.body.data).toHaveProperty('singleFlight');
  });
});
